-- 4) vocab (fuzzy 후보용) - alias/canonical 둘 다 토큰화
CREATE MATERIALIZED VIEW public.industry_vocab AS
WITH tokens AS (
  SELECT lower(btrim(tok)) AS token
  FROM public.industry_alias ia
  CROSS JOIN LATERAL regexp_split_to_table(
    coalesce(ia.alias,'') || ',' ||
 coalesce(ia.canonical,''),
    '\s[,/|]+\s'
  ) AS tok
  WHERE ia.is_active
)
SELECT token, COUNT(*)::bigint AS cnt
FROM tokens
WHERE token <> ''
GROUP BY token;

CREATE UNIQUE INDEX IF NOT EXISTS ux_industry_vocab_token
ON public.industry_vocab (token);

CREATE INDEX IF NOT EXISTS ix_industry_vocab_token_trgm
ON public.industry_vocab USING gin (token gin_trgm_ops);

