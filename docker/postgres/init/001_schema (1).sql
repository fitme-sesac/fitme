/* =========================================================
 * 6) orders
 * ========================================================= */
CREATE TABLE IF NOT EXISTS orders (
  order_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_uid           UUID NOT NULL,
  buyer_type          VARCHAR(20) NOT NULL,
  buyer_member_id     BIGINT NULL REFERENCES member(member_id),
  buyer_employer_id   BIGINT NULL REFERENCES employer(employer_id),
  product_id          BIGINT NOT NULL REFERENCES product(product_id),
  order_amount        NUMERIC(12,2) NOT NULL DEFAULT 0.00,
  status              VARCHAR(20) NOT NULL DEFAULT 'CREATED',
  idempotency_key     VARCHAR(64) NOT NULL,
  created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),

  CONSTRAINT uq_order_uid UNIQUE (order_uid),
  CONSTRAINT uq_orders_idempotency UNIQUE (idempotency_key),
  CONSTRAINT ck_orders_buyer_type CHECK (buyer_type IN ('MEMBER','EMPLOYER')),
  CONSTRAINT ck_orders_status CHECK (status IN ('CREATED','PAID','CANCELED','FAILED')),
  CONSTRAINT ck_orders_buyer_fk
    CHECK (
      (buyer_type = 'MEMBER'   AND buyer_member_id IS NOT NULL AND buyer_employer_id IS NULL) OR
      (buyer_type = 'EMPLOYER' AND buyer_employer_id IS NOT NULL AND buyer_member_id IS NULL)
    )
);


/* =========================================================
 * 7) payment
 * ========================================================= */
CREATE TABLE IF NOT EXISTS payment (
  payment_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_uid         UUID NOT NULL,
  order_id            BIGINT NOT NULL REFERENCES orders(order_id),
  method              VARCHAR(20) NOT NULL,
  paid_amount         NUMERIC(12,2) NOT NULL DEFAULT 0.00,
  app_status          VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
  pg_status           VARCHAR(40) NULL,
  pg_payment_key      VARCHAR(100) NULL,
  pg_approval_key     VARCHAR(80) NULL,
  pg_transaction_id   VARCHAR(80) NULL,
  pg_payload          JSONB NULL,
  approved_at         TIMESTAMPTZ(3) NULL,
  canceled_at         TIMESTAMPTZ(3) NULL,
  created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),

  CONSTRAINT uq_payment_uid UNIQUE (payment_uid),
  CONSTRAINT ck_payment_app_status
    CHECK (app_status IN ('REQUESTED','APPROVED','FAILED','CANCELED','PARTIAL_CANCELED')),
  CONSTRAINT ck_payment_pg_status
    CHECK (
      pg_status IS NULL OR
      pg_status IN (
        'READY','IN_PROGRESS','WAITING_FOR_DEPOSIT','DONE',
        'CANCELED','PARTIAL_CANCELED','ABORTED','EXPIRED'
      )
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_pg_payment_key
  ON payment(pg_payment_key)
  WHERE pg_payment_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_payment_order_id
  ON payment(order_id);


