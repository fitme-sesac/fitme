CREATE INDEX IF NOT EXISTS idx_job_posting_employer_status
  ON job_posting(employer_id, status);

CREATE INDEX IF NOT EXISTS idx_job_posting_stack_gin ON job_posting USING GIN (stack);

CREATE INDEX IF NOT EXISTS idx_job_posting_ads_prefilter
  ON job_posting (stack, ad_bid_credit DESC, job_id)
  WHERE deleted_at IS NULL
    AND status = 'OPEN'
    AND ad_bid_credit > 0;

COMMENT ON COLUMN job_posting.ad_bid_credit IS
'광고 입찰가(credit). RTB 우선순위/AI유사도+비즈가치 하이브리드 스코어/광고만 프리필터링 용도.';
COMMENT ON COLUMN job_posting.required_experience IS '채용을 위해 요구되는 최소 경력 연수 (0: 신입)';


/* =========================================================
 * 14) resume
 * ========================================================= */
CREATE TABLE IF NOT EXISTS resume (
  resume_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id            BIGINT NOT NULL REFERENCES member(member_id),
  title                VARCHAR(120) NOT NULL,
  tagline              VARCHAR(200) NULL,
  is_primary           BOOLEAN NOT NULL DEFAULT FALSE,
  is_public            BOOLEAN NOT NULL DEFAULT FALSE,
  status               VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  last_modified_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  created_at           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at           TIMESTAMPTZ(3) NULL,
  target_job_id        BIGINT NULL REFERENCES job_posting(job_id),
  content              TEXT NULL,
  field                VARCHAR(20) NOT NULL,
  summary              TEXT NULL,
  embedding            vector(1536) NULL,
  summary_status       VARCHAR(20) NOT NULL DEFAULT 'NONE',
  preference_location  VARCHAR(80) NULL,
  preference_salary    VARCHAR(80) NULL,
  employment_type      VARCHAR(80) NULL,
  re_stack            TEXT[] NULL,
  career_years         INT NOT NULL DEFAULT 0,
  school               TEXT NULL,
  school_state         TEXT NULL,
  school_class         TEXT NULL,

  CONSTRAINT ck_resume_status CHECK (status IN ('DRAFT','ACTIVE','DELETED')),
  CONSTRAINT ck_resume_field  CHECK (field IN ('RESUME','PORTFOLIO','INTRO')),
  CONSTRAINT ck_resume_summary_status
    CHECK (summary_status IN ('NONE','PENDING','PROCESSING','COMPLETED','FAILED')),
  CONSTRAINT ck_resume_summary_completed_has_summary
    CHECK (summary_status <> 'COMPLETED' OR summary IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_resume_member_status
  ON resume(member_id, status);

CREATE INDEX IF NOT EXISTS idx_resume_re_stack_gin ON resume USING GIN (re_stack);

CREATE INDEX IF NOT EXISTS idx_resume_summary_todo
  ON resume (summary_status, updated_at DESC, resume_id)
  WHERE summary_status IN ('PENDING','FAILED');

COMMENT ON COLUMN resume.summary_status IS 'AI 요약 비동기 상태: NONE(미요청)/PENDING/PROCESSING/COMPLETED/FAILED';
COMMENT ON COLUMN resume.re_stack IS '사용자가 보유한 기술 스택 목록 (배열)';
COMMENT ON COLUMN resume.career_years IS '사용자가 직접 입력/확정한 직무 관련 총 경력 연수';


