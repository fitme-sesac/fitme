CREATE TABLE IF NOT EXISTS wallet (
  wallet_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_type     VARCHAR(20) NOT NULL,
  member_id      BIGINT NULL REFERENCES member(member_id),
  employer_id    BIGINT NULL REFERENCES employer(employer_id),
  balance        INT NOT NULL DEFAULT 0,
  status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),

  CONSTRAINT ck_wallet_owner_type CHECK (owner_type IN ('MEMBER','EMPLOYER')),
  CONSTRAINT ck_wallet_owner_fk
    CHECK (
      (owner_type='MEMBER'   AND member_id IS NOT NULL AND employer_id IS NULL) OR
      (owner_type='EMPLOYER' AND employer_id IS NOT NULL AND member_id IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_wallet_member_one
  ON wallet(member_id) WHERE member_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_wallet_employer_one
  ON wallet(employer_id) WHERE employer_id IS NOT NULL;


