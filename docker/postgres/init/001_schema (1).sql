DROP MATERIALIZED VIEW IF EXISTS public.stack_vocab;

CREATE MATERIALIZED VIEW public.stack_vocab AS
WITH tokens AS (
  SELECT
    lower(regexp_replace(btrim(tok), E'\s+', ' ', 'g')) AS token
  FROM public.job_posting jp
  CROSS JOIN LATERAL unnest(coalesce(jp.stack, ARRAY[]::text[])) AS s(item)
  CROSS JOIN LATERAL regexp_split_to_table(coalesce(s.item, ''), E'\s[,/|]+\s') AS tok
  WHERE jp.deleted_at IS NULL
    AND jp.status = 'OPEN'
    AND jp.stack IS NOT NULL
)
SELECT token, COUNT(*)::bigint AS cnt
FROM tokens
WHERE token <> ''
  AND length(token) BETWEEN 2 AND 40
  AND token !~ '^[0-9]+$'
  AND token ~ '[a-zA-Z가-힣]'
GROUP BY token
WITH NO DATA;

