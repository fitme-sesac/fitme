CREATE UNIQUE INDEX IF NOT EXISTS ux_stack_vocab_token ON public.stack_vocab(token);

CREATE INDEX IF NOT EXISTS ix_stack_vocab_token_trgm
  ON public.stack_vocab USING GIN (token gin_trgm_ops);

