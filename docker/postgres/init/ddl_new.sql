  CONSTRAINT uq_subscription_billing UNIQUE (subscription_id, billing_month),

  CONSTRAINT ck_cycle_payment_status
    CHECK (payment_status IN ('SCHEDULED','PAID','FAILED')),
  CONSTRAINT ck_cycle_credit_status
    CHECK (credit_status IN ('PENDING','GRANTED','FAILED','REVOKED'))
);


-- =========================================================
-- 13) job_posting (채용공고) ✅ 원본 유지 + 스택 배열화/경력 필드 추가
-- =========================================================
CREATE TABLE job_posting (
  job_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employer_id         BIGINT NOT NULL REFERENCES employer(employer_id),
  title               VARCHAR(200) NOT NULL,
  description         TEXT NOT NULL,
  status              VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  location            VARCHAR(120) NULL,
  salary_text         BIGINT NULL,
  required_questions  JSONB NULL,
  view_count          INT NOT NULL DEFAULT 0,
  apply_count         INT NOT NULL DEFAULT 0,

  -- ✅ 변경: VARCHAR(80) -> TEXT[] (기술 스택 배열)
  stack              TEXT[] NULL,           
  
  -- ✅ 신규 추가: 최소 요구 경력 연수 (0: 신입/무관)
  required_experience INT NOT NULL DEFAULT 0,

  summary             TEXT NULL,             -- 파이썬 요약본
  embedding           vector(1536) NULL,     -- pgvector

  -- ✅ 광고 입찰가(credit): "광고 아님=0" 정규화
  ad_bid_credit       INT NOT NULL DEFAULT 0,

  created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at          TIMESTAMPTZ(3) NULL,

  CONSTRAINT ck_job_posting_status CHECK (status IN ('DRAFT','OPEN','CLOSED')),
  CONSTRAINT ck_job_posting_counts CHECK (view_count >= 0 AND apply_count >= 0),
  CONSTRAINT ck_job_posting_ad_bid_credit_nonneg CHECK (ad_bid_credit >= 0)
);

CREATE INDEX idx_job_posting_employer_status
  ON job_posting(employer_id, status);

-- ✅ 변경: stack -> stack (배열 타입 반영) 및 GIN 인덱스 추가
CREATE INDEX idx_job_posting_stack_gin ON job_posting USING GIN (stack);

-- ✅ 0.1초 이내 프리필터링: OPEN + 광고(credit>0)만 먼저 추출 (stack 필드 반영)
CREATE INDEX idx_job_posting_ads_prefilter
  ON job_posting (stack, ad_bid_credit DESC, job_id)
  WHERE deleted_at IS NULL
    AND status = 'OPEN'
    AND ad_bid_credit > 0;

COMMENT ON COLUMN job_posting.ad_bid_credit IS
'광고 입찰가(credit). RTB 우선순위/AI유사도+비즈가치 하이브리드 스코어/광고만 프리필터링 용도.';
COMMENT ON COLUMN job_posting.required_experience IS '채용을 위해 요구되는 최소 경력 연수 (0: 신입)';


