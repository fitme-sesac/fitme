-- PostgreSQL DDL (요구사항 반영 + "정책 동의" 테이블 추가 없이 처리)
-- ✅ 정책 동의 방식:
--   - notice 테이블을 "공지(OPS) + 정책문서(TERMS/PRIVACY/POLICY)" 저장소로 재사용
--   - member 테이블에 "동의한 notice_id + 동의 시각(+ ip/ua)"만 컬럼으로 보관
--   - member -> notice FK는 notice 생성 이후 ALTER TABLE로 추가(순환 참조 방지)
--
-- ✅ 이번 반영 핵심:
--   - job_posting.ad_bid_credit: "광고 아님=0" 정규화 (DEFAULT 0 + NOT NULL + CHECK >=0)
--   - job_posting 광고 프리필터링 부분 인덱스 추가 (status=OPEN, ad_bid_credit>0)
--   - resume.summary_status: DEFAULT/CK 불일치 수정 (NONE 포함)
--   - resume.emploment_type 오탈자 수정 -> employment_type
--   - updated_at 자동 갱신 트리거 전략 추가
--
-- =========================================================
-- Extensions
-- =========================================================
CREATE EXTENSION IF NOT EXISTS pgcrypto;  -- gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS vector;    -- pgvector
-- =========================================================
-- updated_at 자동 갱신 전략 (트리거)
-- =========================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;


/* =========================================================
 * 1) member (회원 기본 + 보안 상태)  ✅ login_id + 정책동의 컬럼
 *    ✅ phone NULL 허용 (소셜 사용자 추후 연결)
 *    ✅ gender / birth_date 추가 (나이는 birth_date로 계산)
 * ========================================================= */
CREATE TABLE member (
  member_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_uid              UUID NOT NULL,                 -- 앱 생성(UUID)
  email                   VARCHAR(320) NOT NULL,
  login_id                VARCHAR(50) NULL,              -- 소셜은 NULL 허용
  auth_provider           VARCHAR(20) NOT NULL DEFAULT 'OTHER', -- NAVER/GOOGLE/KAKAO/OTHER
  password_hash           VARCHAR(255) NULL,             -- 소셜 전용이면 NULL

  name                    VARCHAR(80) NOT NULL,

  -- ✅ A안: 개인정보는 member가 원천
  gender                  VARCHAR(20) NULL,              -- MALE/FEMALE
  birth_date              DATE NULL,                     -- 나이는 birth_date로 계산

  phone                   VARCHAR(20) NULL,              -- ✅ NULL 허용(소셜 사용자 추후 연결)
  role                    VARCHAR(20) NOT NULL,
  status                  VARCHAR(20) NOT NULL,

  last_login_at           TIMESTAMPTZ(3) NULL,
  password_changed_at     TIMESTAMPTZ(3) NULL,
  failed_login_count      INT NOT NULL DEFAULT 0,
  locked_until            TIMESTAMPTZ(3) NULL,

  -- ✅ 휴대폰 OTP 인증 완료 시각(점유 확인)
  phone_verified_at       TIMESTAMPTZ(3) NULL,

  created_at              TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at              TIMESTAMPTZ(3) NULL,

  -- ✅ 정책 동의(테이블 추가 없이) : notice(notice_id) 참조 예정
  -- FK 제약은 notice 생성 이후 ALTER TABLE로 추가
  terms_notice_id         BIGINT NULL,
  terms_agreed_at         TIMESTAMPTZ(3) NULL,
  privacy_notice_id       BIGINT NULL,
  privacy_agreed_at       TIMESTAMPTZ(3) NULL,
  policy_notice_id        BIGINT NULL,
  policy_agreed_at        TIMESTAMPTZ(3) NULL,

  marketing_opt_in        BOOLEAN NOT NULL DEFAULT FALSE,
  marketing_agreed_at     TIMESTAMPTZ(3) NULL,

  consent_ip              VARCHAR(45) NULL,   -- IPv4/IPv6
  consent_user_agent      TEXT NULL,

  CONSTRAINT uq_member_uid UNIQUE (member_uid),
  CONSTRAINT uq_member_email UNIQUE (email),

  CONSTRAINT ck_member_role
    CHECK (role IN ('CANDIDATE','EMPLOYER','SERVICEADMIN','APPROVEADMIN','MASTER')),
  CONSTRAINT ck_member_status
    CHECK (status IN ('ACTIVE','SUSPENDED','WITHDRAWN')),
  CONSTRAINT ck_member_failed_login_count
    CHECK (failed_login_count >= 0),

  CONSTRAINT ck_member_auth_provider
    CHECK (auth_provider IN ('NAVER','GOOGLE','KAKAO','OTHER')),

  CONSTRAINT ck_member_gender
    CHECK (gender IS NULL OR gender IN ('MALE','FEMALE')),

  CONSTRAINT ck_member_phone_verified_requires_phone
    CHECK (phone_verified_at IS NULL OR phone IS NOT NULL),

  -- ✅ ACTIVE 상태는 필수 동의가 있어야 함(운영 정책에 맞게 조정 가능)
  CONSTRAINT ck_member_required_consents
    CHECK (
      status <> 'ACTIVE'
      OR (
        terms_notice_id   IS NOT NULL AND terms_agreed_at   IS NOT NULL AND
        privacy_notice_id IS NOT NULL AND privacy_agreed_at IS NOT NULL
      )
    ),

  CONSTRAINT ck_member_marketing_optin_time
    CHECK (
      marketing_opt_in IS FALSE
      OR (marketing_opt_in IS TRUE AND marketing_agreed_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_member_login_id_active
  ON member (login_id)
  WHERE deleted_at IS NULL AND login_id IS NOT NULL;

CREATE UNIQUE INDEX uq_member_phone_verified_active
  ON member (phone)
  WHERE deleted_at IS NULL
    AND phone IS NOT NULL
    AND phone_verified_at IS NOT NULL;


/* =========================================================
 * 1-1) phone_verification (휴대폰 OTP 인증)
 * ========================================================= */
CREATE TABLE phone_verification (
  verification_id     UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  phone               VARCHAR(20) NOT NULL,
  purpose             VARCHAR(20) NOT NULL,      -- SIGNUP / PASSWORD_RESET / PHONE_LINK
  code_hash           CHAR(64) NOT NULL,         -- HMAC-SHA256 hex 등

  expires_at          TIMESTAMPTZ(3) NOT NULL,
  verified_at         TIMESTAMPTZ(3) NULL,
  consumed_at         TIMESTAMPTZ(3) NULL,

  attempt_count       INT NOT NULL DEFAULT 0,
  resend_count        INT NOT NULL DEFAULT 0,
  last_sent_at        TIMESTAMPTZ(3) NOT NULL DEFAULT now(),

  request_ip          VARCHAR(45) NULL,
  request_user_agent  TEXT NULL,

  created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),

  CONSTRAINT ck_phone_verification_purpose
    CHECK (purpose IN ('SIGNUP','PASSWORD_RESET','PHONE_LINK')),
  CONSTRAINT ck_phone_verification_attempt
    CHECK (attempt_count >= 0),
  CONSTRAINT ck_phone_verification_resend
    CHECK (resend_count >= 0),
  CONSTRAINT ck_phone_verification_phone_digits
    CHECK (phone ~ '^[0-9]{10,15}$')
);

CREATE INDEX idx_phone_verification_phone_purpose_created
  ON phone_verification(phone, purpose, created_at DESC);

CREATE INDEX idx_phone_verification_active
  ON phone_verification(phone, purpose, expires_at)
  WHERE consumed_at IS NULL;


