/* =========================================================
 * 7) payment (결제) - 내부/PG 상태 분리
 * ========================================================= */
CREATE TABLE payment (
  payment_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_uid         UUID NOT NULL,

  order_id            BIGINT NOT NULL REFERENCES orders(order_id),

  method              VARCHAR(20) NOT NULL,
  paid_amount         NUMERIC(12,2) NOT NULL DEFAULT 0.00,

  -- 내부(앱) 상태
  app_status          VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',

  -- PG(토스) 원문 status (READY~EXPIRED 등)
  pg_status           VARCHAR(40) NULL,

  -- 토스 paymentKey 전용 컬럼
  pg_payment_key      VARCHAR(100) NULL,

  pg_approval_key     VARCHAR(80) NULL,
  pg_transaction_id   VARCHAR(80) NULL,
  pg_payload          JSONB NULL,

  approved_at         TIMESTAMPTZ(3) NULL,
  canceled_at         TIMESTAMPTZ(3) NULL,

  created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),

  CONSTRAINT uq_payment_uid UNIQUE (payment_uid),

  CONSTRAINT ck_payment_app_status
    CHECK (app_status IN ('REQUESTED','APPROVED','FAILED','CANCELED','PARTIAL_CANCELED')),

  CONSTRAINT ck_payment_pg_status
    CHECK (
      pg_status IS NULL OR
      pg_status IN (
        'READY','IN_PROGRESS','WAITING_FOR_DEPOSIT','DONE',
        'CANCELED','PARTIAL_CANCELED','ABORTED','EXPIRED'
      )
    )
);

CREATE UNIQUE INDEX uq_payment_pg_payment_key
  ON payment(pg_payment_key)
  WHERE pg_payment_key IS NOT NULL;

CREATE INDEX idx_payment_order_id
  ON payment(order_id);


