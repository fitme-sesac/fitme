-- 15) job_posting
CREATE TABLE IF NOT EXISTS job_posting (
  job_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employer_id         BIGINT NOT NULL REFERENCES employer(employer_id),
  title               VARCHAR(200) NOT NULL,
  description         TEXT NOT NULL,
  status              VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  location            VARCHAR(120) NULL,
  salary_text         VARCHAR(80) NULL,
  required_questions  JSONB NULL,
  view_count          INT NOT NULL DEFAULT 0,
  apply_count         INT NOT NULL DEFAULT 0,
  stack               TEXT[] NULL,
  required_experience INT NOT NULL DEFAULT 0,
  summary             TEXT NULL,
  embedding           vector(1536) NULL,
  ad_bid_credit       INT NOT NULL DEFAULT 0,
  recruitment_capacity INT NOT NULL DEFAULT 0,
  created_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at          TIMESTAMPTZ(3) NULL,
  CONSTRAINT ck_job_posting_status CHECK (status IN ('DRAFT','OPEN','CLOSED')),
  CONSTRAINT ck_job_posting_counts CHECK (view_count >= 0 AND apply_count >= 0),
  CONSTRAINT ck_job_posting_ad_bid_credit_nonneg CHECK (ad_bid_credit >= 0),
  CONSTRAINT ck_job_posting_recruitment_capacity CHECK (recruitment_capacity >= 0)
);

CREATE INDEX IF NOT EXISTS idx_job_posting_employer_status ON job_posting(employer_id, status);
CREATE INDEX IF NOT EXISTS idx_job_posting_stack_gin ON job_posting USING GIN (stack);


-- 16) resume
CREATE TABLE IF NOT EXISTS resume (
  resume_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id            BIGINT NOT NULL REFERENCES member(member_id),
  title                VARCHAR(120) NOT NULL,
  tagline              VARCHAR(200) NULL,
  is_primary           BOOLEAN NOT NULL DEFAULT FALSE,
  is_public            BOOLEAN NOT NULL DEFAULT FALSE,
  status               VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  last_modified_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  created_at           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at           TIMESTAMPTZ(3) NULL,
  target_job_id        BIGINT NULL REFERENCES job_posting(job_id),
  content              TEXT NULL,
  field                VARCHAR(20) NOT NULL DEFAULT 'RESUME',
  summary              TEXT NULL,
  embedding            vector(1536) NULL,
  summary_status       VARCHAR(20) NOT NULL DEFAULT 'NONE',
  preference_location  VARCHAR(80) NULL,
  preference_salary    VARCHAR(80) NULL,
  employment_type      VARCHAR(80) NULL,
  re_stack             TEXT[] NULL,
  career_years         INT NOT NULL DEFAULT 0,
  school               TEXT NULL,
  school_state         TEXT NULL,
  school_class         TEXT NULL,
  CONSTRAINT ck_resume_status CHECK (status IN ('DRAFT','ACTIVE','DELETED')),
  CONSTRAINT ck_resume_field CHECK (field IN ('RESUME','PORTFOLIO','INTRO')),
  CONSTRAINT ck_resume_summary_status CHECK (summary_status IN ('NONE','PENDING','PROCESSING','COMPLETED','FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_resume_member_status ON resume(member_id, status);
CREATE INDEX IF NOT EXISTS idx_resume_re_stack_gin ON resume USING GIN (re_stack);


