-- 6) employer_member
CREATE TABLE IF NOT EXISTS employer_member (
  employer_member_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employer_id          BIGINT NOT NULL REFERENCES employer(employer_id),
  member_id            BIGINT NOT NULL REFERENCES member(member_id),
