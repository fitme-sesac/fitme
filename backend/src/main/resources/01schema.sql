-- 1) notice (member FK 참조용으로 먼저 생성)
CREATE TABLE IF NOT EXISTS notice (
  notice_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title          VARCHAR(200) NOT NULL,
  body           TEXT NOT NULL,
  is_public      BOOLEAN NOT NULL DEFAULT TRUE,
  notice_type    VARCHAR(30) NOT NULL DEFAULT 'OPS',
  status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  purge_after    TIMESTAMPTZ(3) NULL,
  created_by     BIGINT NULL,
  updated_by     BIGINT NULL,
  created_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at     TIMESTAMPTZ(3) NULL,
  CONSTRAINT ck_notice_type CHECK (notice_type IN ('OPS','POLICY','PRIVACY','TERMS')),
  CONSTRAINT ck_notice_status CHECK (status IN ('ACTIVE','PENDING_DELETE','DELETED'))
);

CREATE INDEX IF NOT EXISTS idx_notice_type_status_created ON notice(notice_type, status, created_at DESC);


-- 2) member
CREATE TABLE IF NOT EXISTS member (
  member_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_uid              UUID NOT NULL,
  email                   VARCHAR(320) NOT NULL,
  login_id                VARCHAR(50) NULL,
  auth_provider           VARCHAR(20) NOT NULL DEFAULT 'OTHER',
  password_hash           VARCHAR(255) NULL,
  name                    VARCHAR(80) NOT NULL,
  gender                  VARCHAR(20) NULL,
  birth_date              DATE NULL,
  phone                   VARCHAR(20) NULL,
  role                    VARCHAR(20) NOT NULL,
  status                  VARCHAR(20) NOT NULL,
  last_login_at           TIMESTAMPTZ(3) NULL,
  password_changed_at     TIMESTAMPTZ(3) NULL,
  failed_login_count      INT NOT NULL DEFAULT 0,
  locked_until            TIMESTAMPTZ(3) NULL,
  phone_verified_at       TIMESTAMPTZ(3) NULL,
  created_at              TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at              TIMESTAMPTZ(3) NULL,
  terms_notice_id         BIGINT NULL REFERENCES notice(notice_id),
  terms_agreed_at         TIMESTAMPTZ(3) NULL,
  privacy_notice_id       BIGINT NULL REFERENCES notice(notice_id),
  privacy_agreed_at       TIMESTAMPTZ(3) NULL,
  policy_notice_id        BIGINT NULL REFERENCES notice(notice_id),
  policy_agreed_at        TIMESTAMPTZ(3) NULL,
  marketing_opt_in        BOOLEAN NOT NULL DEFAULT FALSE,
  marketing_agreed_at     TIMESTAMPTZ(3) NULL,
  consent_ip              VARCHAR(45) NULL,
  consent_user_agent      TEXT NULL,
  CONSTRAINT uq_member_uid UNIQUE (member_uid),
  CONSTRAINT uq_member_email UNIQUE (email),
  CONSTRAINT ck_member_role CHECK (role IN ('CANDIDATE','EMPLOYER','SERVICEADMIN','APPROVEADMIN','MASTER')),
  CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE','SUSPENDED','WITHDRAWN')),
  CONSTRAINT ck_member_failed_login_count CHECK (failed_login_count >= 0),
  CONSTRAINT ck_member_auth_provider CHECK (auth_provider IN ('NAVER','GOOGLE','KAKAO','OTHER')),
  CONSTRAINT ck_member_gender CHECK (gender IS NULL OR gender IN ('MALE','FEMALE'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_member_login_id_active ON member(login_id) WHERE deleted_at IS NULL AND login_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_member_phone_verified_active ON member(phone) WHERE deleted_at IS NULL AND phone IS NOT NULL AND phone_verified_at IS NOT NULL;


-- 3) phone_verification
CREATE TABLE IF NOT EXISTS phone_verification (
  verification_id     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  phone               VARCHAR(20) NOT NULL,
  purpose             VARCHAR(20) NOT NULL,
  code_hash           CHAR(64) NOT NULL,
  expires_at          TIMESTAMPTZ(3) NOT NULL,
  verified_at         TIMESTAMPTZ(3) NULL,
  consumed_at         TIMESTAMPTZ(3) NULL,
  attempt_count       INT NOT NULL DEFAULT 0,
  resend_count        INT NOT NULL DEFAULT 0,
  last_sent_at        TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
